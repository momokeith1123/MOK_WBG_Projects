select  BOOK_CURRENCY_CODE,
    BOOK_CODE,
    PORTFOLIO_TYPE_CODE,
    TO_CHAR(AS_OF_DATE,'YYYYMMDD') AS AS_OF_DATE,
    TO_CHAR (LAST_RUN_DT, 'YYYYMMDD') as LAST_RUN_DT,   
    LAST_VERSION_NBR,
    NOTIONAL_VALUE_AMT,
    NOTIONAL_VALUE_RPT_CCY_AMT,
    HOLDING_VALUE_AMT,
    HOLDING_VALUE_RPT_CCY_AMT,
    CASH_BALANCE_AMT,
    CASH_BAL_RPT_CCY_AMT,
    EXTERNAL_CF_AMT,
    NET_ASSET_VALUE_AMT,
    NET_ASSET_VALUE_RPT_CCY_AMT,    
    PERFORMANCE_INDEX_VAL,
    EXCESS_RETURN_VAL,
    EXCESS_INCOME_AMT   
from CURR_PORTFOLIO_PERF_V
    WHERE AS_OF_DATE >= TO_DATE('30/06/2025','DD/MM/YYYY')
    and PORTFOLIO_TYPE_CODE = 'A'
    and BOOK_CODE = 'P1'
order by as_of_date ;

